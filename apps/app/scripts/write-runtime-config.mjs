// Writes config.json into the built web assets before `cap sync`, so native apps know which API to call, and the
// iOS build's Google sign-in URL scheme.
import { rmSync, writeFileSync } from 'node:fs';

const release = process.env.GRASP_RELEASE === '1';
const apiUrl = process.env.GRASP_API_URL || null;
const googleIosClientId = process.env.GRASP_GOOGLE_IOS_CLIENT_ID || null;
const googleIosClientPrefix = googleIosClientId?.match(/^([A-Za-z0-9-]+)\.apps\.googleusercontent\.com$/)?.[1];

if (release && !apiUrl?.startsWith('https://')) {
  console.error('Release builds need GRASP_API_URL set to an https URL, e.g. GRASP_API_URL=https://grasp.example.com/api');
  process.exit(1);
}
if (googleIosClientId && !googleIosClientPrefix) {
  console.error(
    'GRASP_GOOGLE_IOS_CLIENT_ID must be an iOS OAuth client id, e.g. GRASP_GOOGLE_IOS_CLIENT_ID=1234-abcd.apps.googleusercontent.com',
  );
  process.exit(1);
}

const config = {
  apiUrl,
  sentryDsn: process.env.GRASP_SENTRY_DSN || null,
  // iOS offers Google only when this matches the server's iOS client, whose reversed id this build registered.
  googleIosClientId,
  environment: release ? 'production' : 'development',
  release: process.env.GRASP_VERSION || null,
  // The Python runtime (~14 MB) is fetched from the server on first use instead of bloating the app bundle.
  pyodideUrl: apiUrl ? new URL('/pyodide/', apiUrl).href : null,
};
const web = new URL('../dist/app/browser/', import.meta.url);
writeFileSync(new URL('config.json', web), `${JSON.stringify(config, null, 2)}\n`);
if (apiUrl) rmSync(new URL('pyodide', web), { recursive: true, force: true });

// GoogleSignIn crashes the app when the iOS client's reversed id is not a registered URL scheme, so the scheme
// comes from the same variable as googleIosClientId. The placeholder keeps builds without a client valid.
const googleUrlScheme = googleIosClientPrefix ? `com.googleusercontent.apps.${googleIosClientPrefix}` : 'dev.grasp.app.google-unset';
writeFileSync(
  new URL('../ios/google-signin.xcconfig', import.meta.url),
  `// Generated by apps/app/scripts/write-runtime-config.mjs from GRASP_GOOGLE_IOS_CLIENT_ID.\nGOOGLE_IOS_URL_SCHEME = ${googleUrlScheme}\n`,
);

console.log(`Runtime config: API ${apiUrl ?? '(platform default)'}, iOS Google client ${googleIosClientId ?? '(none)'}`);
