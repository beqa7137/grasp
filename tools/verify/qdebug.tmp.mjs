import { launch, newContext } from './lib.mjs';
const browser = await launch();
const ctx = await newContext(browser, 'desktop');
const logs = [];
const p = await ctx.newPage();
p.on('console', (m) => console.log('console', m.type(), m.text()));
p.on('pageerror', (e) => console.log('pageerror', String(e)));
await p.goto('http://localhost:4433/design/topics/sd-consistency');
await p.locator('app-quorum-widget svg.draw').waitFor();
await p.locator('app-quorum-widget .cards button', { hasText: 'Challenge' }).click();
const w = p.locator('app-quorum-widget');
await w.getByRole('radio', { name: '5 replicas' }).check();
await p.waitForTimeout(600);
console.log(await w.locator('.status').textContent(), await w.locator('svg.draw').getAttribute('aria-label'));
await p.getByRole('slider', { name: 'W, acks a write waits for', exact: true }).focus();
await p.keyboard.press('ArrowRight');
await p.waitForTimeout(600);
console.log(await w.locator('.status').textContent(), await w.locator('svg.draw').getAttribute('aria-label'));
await p.getByRole('slider', { name: 'R, answers a read waits for', exact: true }).focus();
await p.keyboard.press('ArrowLeft');
await p.waitForTimeout(600);
console.log(await w.locator('.status').textContent(), await w.locator('svg.draw').getAttribute('aria-label'));
console.log(await w.getByRole('slider').evaluateAll((s) => s.map((x) => x.getAttribute('aria-valuetext'))));
await browser.close();
