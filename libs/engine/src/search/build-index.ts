import { ALGORITHM_CATALOG } from '../algorithms/catalog.js';
import { COMPETENCY_CATALOG } from '../behavioral/catalog.js';
import { COMPETENCIES } from '../behavioral/competencies.js';
import { CODING_CATALOG } from '../coding/catalog.js';
import { PATTERN_CATALOG } from '../curriculum/catalog.js';
import { SD_TOPICS } from '../curriculum/sd-topics.js';
import { MOCK_PROBLEMS } from '../interview/mock-problems.js';
import { CASE_BRIEFS } from '../sysdesign/case-briefs.js';
import { CASE_CATALOG } from '../sysdesign/case-catalog.js';
import { SCENARIO_CATALOG } from '../sysdesign/scenario-catalog.js';
import { CUE_WORDS, SEARCH_ALIASES } from './keywords.js';
import type { IndexedKind, SearchKind, SearchRow } from './types.js';

const row = (kind: SearchKind, id: string, title: string, blurb: string, tags: readonly string[] = []): SearchRow => {
  const key = `${kind}:${id}`;
  const aliases = [...(SEARCH_ALIASES[key] ?? []), ...(CUE_WORDS[key] ?? [])];
  if (aliases.length) return [id, title, blurb, tags, aliases];
  return tags.length ? [id, title, blurb, tags] : [id, title, blurb];
};

/** The search index (REDESIGN.md 2.9): titles, short blurbs, tags and aliases only, drawn from the catalogs. */
export function buildSearchIndex(): Record<IndexedKind, SearchRow[]> {
  const brief = new Map(CASE_BRIEFS.map((b) => [b.id, b.summary]));
  return {
    pattern: PATTERN_CATALOG.map((p) => row('pattern', p.id, p.name, p.oneLiner)),
    visualizer: ALGORITHM_CATALOG.map((a) => row('visualizer', a.id, a.title, '', [a.patternId])),
    problem: CODING_CATALOG.map((p) => row('problem', p.id, p.title, p.difficulty, p.patternIds)),
    topic: SD_TOPICS.map((t) => row('topic', t.id, t.name, t.oneLiner)),
    mission: SCENARIO_CATALOG.map((s) =>
      row(
        'mission',
        s.id,
        s.title,
        s.tagline,
        SD_TOPICS.filter((t) => t.scenarioIds.includes(s.id)).map((t) => t.id),
      ),
    ),
    case: CASE_CATALOG.map((c) => row('case', c.id, c.title, brief.get(c.id) ?? '', c.topics)),
    mock: MOCK_PROBLEMS.map((m) => row('mock', m.id, m.title, '', [m.track])),
    competency: COMPETENCY_CATALOG.map((c) => row('competency', c.id, c.name, c.oneLiner)),
  };
}

/** The 91 question prompts as [id, prompt], so lists and search read them without the competency guides. */
export function buildQuestionPrompts(): [id: string, prompt: string][] {
  return COMPETENCIES.flatMap((c) => c.questions.map((q): [string, string] => [q.id, q.prompt]));
}

const GENERATED = '// Generated by `npm run gen:search` from the engine catalogs; edit those, then run it. A spec fails when this is stale.';

/** The index module's source, before formatting. */
export function searchIndexSource(): string {
  return `${GENERATED}
import type { IndexedKind, SearchRow } from './types.js';

export const SEARCH_DATA: Readonly<Record<IndexedKind, readonly SearchRow[]>> = ${JSON.stringify(buildSearchIndex())};
`;
}

/** The prompts module's source, before formatting. */
export function questionPromptsSource(): string {
  return `${GENERATED}
export const QUESTION_PROMPT_ROWS: readonly (readonly [id: string, prompt: string])[] = ${JSON.stringify(buildQuestionPrompts())};
`;
}
