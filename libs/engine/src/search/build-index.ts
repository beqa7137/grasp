import { COMPETENCIES } from '../behavioral/competencies.js';
import { CODING_CATALOG } from '../coding/catalog.js';
import { CASE_BRIEFS } from '../sysdesign/case-briefs.js';
import type { SearchData } from './types.js';

/**
 * What search needs from modules that do not load with first paint (REDESIGN.md 2.9): problem titles and difficulties, case
 * summaries, and the question prompts. The rest it reads from the catalogs first paint already holds.
 */
export function buildSearchData(): SearchData {
  return {
    problem: CODING_CATALOG.map((p) => [p.id, p.title, p.difficulty]),
    caseSummary: CASE_BRIEFS.map((b) => [b.id, b.summary]),
  };
}

/** The 91 question prompts as [id, prompt], so lists and search read them without the competency guides. */
export function buildQuestionPrompts(): [id: string, prompt: string][] {
  return COMPETENCIES.flatMap((c) => c.questions.map((q): [string, string] => [q.id, q.prompt]));
}

const GENERATED = '// Generated by `npm run gen:search` from the engine catalogs; edit those, then run it. A spec fails when this is stale.';

/** The index module's source, before formatting. */
export function searchDataSource(): string {
  return `${GENERATED}
import type { SearchData } from './types.js';

export const SEARCH_DATA: SearchData = ${JSON.stringify(buildSearchData())};
`;
}

/** The prompts module's source, before formatting. */
export function questionPromptsSource(): string {
  return `${GENERATED}
export const QUESTION_PROMPT_ROWS: readonly (readonly [id: string, prompt: string])[] = ${JSON.stringify(buildQuestionPrompts())};
`;
}
